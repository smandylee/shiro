const EMOTION_TAG_RE = /^\s*\[emotion:([a-z]+)\]\s*/i;

export function parseEmotionTag(raw: string): { emotion: Emotion; text: string } {
  const match = raw.match(EMOTION_TAG_RE);
  const text = raw.replace(EMOTION_TAG_RE, "").trim();
  const candidate = match?.[1]?.toLowerCase();
  const emotion = (EMOTIONS as readonly string[]).includes(candidate ?? "")
    ? (candidate as Emotion)
    : "neutral";
  return { emotion, text: text || raw.trim() };
}
